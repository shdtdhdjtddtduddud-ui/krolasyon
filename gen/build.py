"""Generates textures + Java model layer/animation classes into the mod source tree."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import warden, wolf, extras, revenge, demon, aigoar, tide_fx

ROOT = os.path.join(os.path.dirname(__file__), '..')
TEX = os.path.join(ROOT, 'src/main/resources/assets/krolasyonbosses/textures/entity')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/bosses/client/model')
os.makedirs(TEX, exist_ok=True)
os.makedirs(JAVA, exist_ok=True)

layers = []
for name, model, painter in (('seal_warden', warden.M, warden.P), ('crimson_hound', wolf.M, wolf.P),
                             ('crystal_spike', extras.CS, extras.CSP), ('fire_pillar', extras.FP, extras.FPP),
                             ('watcher', extras.WO, extras.WOP), ('revenge', revenge.M, revenge.P), ('heart_demon', demon.M, demon.P),
                             ('blood_spike', extras.BS, extras.BSP), ('thorn_spike', extras.TS, extras.TSP), ('blood_lance', extras.BL, extras.BLP),
                             ('aigoar', aigoar.M, aigoar.P), ('tide_geyser', tide_fx.GM, tide_fx.GP)):
    model.pack()
    tex, glow = painter.run().images()
    tex.save(os.path.join(TEX, f'{name}.png'))
    glow.save(os.path.join(TEX, f'{name}_glow.png'))
    fn = ''.join(p.capitalize() for p in name.split('_'))
    layers.append(f"""    public static LayerDefinition create{fn}() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{model.java_layer()}
        return LayerDefinition.create(mesh, {model.tw}, {model.th});
    }}
""")
extras.prison_rune().save(os.path.join(TEX, 'seal_prison.png'))
tide_fx.strip(128, 64, 'vortex').save(os.path.join(TEX, 'tide_vortex.png'))
tide_fx.strip(128, 64, 'wave').save(os.path.join(TEX, 'tide_wave.png'))
GUI = os.path.join(ROOT, 'src/main/resources/assets/krolasyonbosses/textures/gui')
ITEM = os.path.join(ROOT, 'src/main/resources/assets/krolasyonbosses/textures/item')
os.makedirs(GUI, exist_ok=True); os.makedirs(ITEM, exist_ok=True)
tide_fx.icons().save(os.path.join(GUI, 'aigoar_abilities.png'))
tide_fx.sword().save(os.path.join(ITEM, 'tide_blade.png'))

with open(os.path.join(JAVA, 'ModelLayers.java'), 'w') as f:
    f.write("""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.bosses.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

@SuppressWarnings("unused")
public final class ModelLayers {
    private ModelLayers() {}

""" + "\n".join(layers) + "}\n")

for cls, mod in (('SealWardenAnimations', warden), ('CrimsonHoundAnimations', wolf), ('RevengeAnimations', revenge), ('HeartDemonAnimations', demon), ('AigoarAnimations', aigoar)):
    body = "\n\n".join(a.java(k) for k, a in mod.A.items())
    with open(os.path.join(JAVA, f'{cls}.java'), 'w') as f:
        f.write(f"""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.bosses.client.model;

import net.minecraft.client.animation.AnimationChannel;
import net.minecraft.client.animation.AnimationDefinition;
import net.minecraft.client.animation.Keyframe;
import net.minecraft.client.animation.KeyframeAnimations;

public final class {cls} {{
    private {cls}() {{}}

{body}
}}
""")
print('generated')
