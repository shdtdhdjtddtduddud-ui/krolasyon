"""Builds item textures, item models, lang and the Java item table.  python3 gen/build_items.py"""
import os, sys, json
sys.path.insert(0, os.path.dirname(__file__))
from sprites import Canvas
from items_materials import MATERIALS
import items_gear as G

ROOT = os.path.join(os.path.dirname(__file__), '..')
ASSETS = os.path.join(ROOT, 'src/main/resources/assets/krolasyonbosses')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/bosses/registry')
os.makedirs(ASSETS + '/textures/item', exist_ok=True)
os.makedirs(ASSETS + '/models/item', exist_ok=True)


def load(p):
    return json.load(open(p)) if os.path.exists(p) else {}


en = load(f'{ASSETS}/lang/en_us.json')
tr = load(f'{ASSETS}/lang/tr_tr.json')
rows = []


def emit_generated(iid, canvas_fn, size=16, parent='minecraft:item/generated'):
    c = canvas_fn(Canvas(size))
    c.to_image().save(f'{ASSETS}/textures/item/{iid}.png')
    with open(f'{ASSETS}/models/item/{iid}.json', 'w') as f:
        json.dump({'parent': parent, 'textures': {'layer0': f'krolasyonbosses:item/{iid}'}}, f)


for iid, ttr, ten, fn, rarity in MATERIALS:
    emit_generated(iid, fn)
    en[f'item.krolasyonbosses.{iid}'] = ten
    tr[f'item.krolasyonbosses.{iid}'] = ttr
    rows.append((iid, rarity))

gear = []
for sid, ttr, ten, fn, dmg, spd, rar, mana, cd in G.SWORDS:
    emit_generated(sid, fn, 32, 'minecraft:item/handheld')
    en[f'item.krolasyonbosses.{sid}'] = ten; tr[f'item.krolasyonbosses.{sid}'] = ttr
    gear.append((sid, 'sword', dmg, spd, rar, mana, cd))
for spell, ttr, ten, cover, trim, emb, mana, cd, rar in G.TOMES:
    iid = 'tome_' + spell
    emit_generated(iid, lambda c, cover=cover, trim=trim, emb=emb: G._tome(c, cover, trim, emb))
    en[f'item.krolasyonbosses.{iid}'] = ten; tr[f'item.krolasyonbosses.{iid}'] = ttr
    gear.append((iid, 'tome', 0, 0, rar, mana, cd))
emit_generated('chronicle', G.chronicle)
with open(f'{JAVA}/GearTable.java', 'w') as f:
    f.write('// GENERATED by gen/build_items.py - do not edit by hand\npackage com.krolasyon.bosses.registry;\n\npublic final class GearTable {\n    private GearTable() {}\n\n'
            '    /** id, kind, attack bonus, attack speed modifier, rarity, mana cost, cooldown ticks */\n    public static final Object[][] ROWS = {\n'
            + ''.join(f'        {{"{i}", "{k}", {d}F, {s}F, "{r}", {m}, {c}}},\n' for i, k, d, s, r, m, c in gear) + '    };\n}\n')

with open(f'{JAVA}/MaterialTable.java', 'w') as f:
    f.write('// GENERATED by gen/build_items.py - do not edit by hand\npackage com.krolasyon.bosses.registry;\n\nfinal class MaterialTable {\n    private MaterialTable() {}\n\n'
            '    /** id, rarity */\n    static final String[][] ROWS = {\n' + ''.join(f'        {{"{i}", "{r}"}},\n' for i, r in rows) + '    };\n}\n')
json.dump(en, open(f'{ASSETS}/lang/en_us.json', 'w'), indent=1, ensure_ascii=False)
json.dump(tr, open(f'{ASSETS}/lang/tr_tr.json', 'w'), indent=1, ensure_ascii=False)
print('items:', len(rows))

# ------------------------------------------------------------ recipes
import shutil
RD = os.path.join(ROOT, 'src/main/resources/data/krolasyonbosses/recipes')
shutil.rmtree(RD, ignore_errors=True)
os.makedirs(RD)
K = lambda i: 'krolasyonbosses:' + i


def ing(x):
    return {'item': x if ':' in x else K(x)}


def shaped(name, pattern, key, result, count=1):
    json.dump({'type': 'minecraft:crafting_shaped', 'category': 'equipment', 'pattern': pattern, 'key': {k: ing(v) for k, v in key.items()}, 'result': {'item': K(result), 'count': count}}, open(f'{RD}/{name}.json', 'w'), indent=1)


def shapeless(name, items, result, count=1):
    json.dump({'type': 'minecraft:crafting_shapeless', 'category': 'misc', 'ingredients': [ing(i) for i in items], 'result': {'item': K(result), 'count': count}}, open(f'{RD}/{name}.json', 'w'), indent=1)


def cook(name, kind, src, result, xp, t):
    json.dump({'type': f'minecraft:{kind}', 'category': 'misc', 'ingredient': ing(src), 'result': K(result), 'experience': xp, 'cookingtime': t}, open(f'{RD}/{name}.json', 'w'), indent=1)


for src in ('raw_hellsteel', 'hellsteel_ore'):
    cook(f'ingot_from_{src}_smelt', 'smelting', src, 'hellsteel_ingot', 1.0, 200)
    cook(f'ingot_from_{src}_blast', 'blasting', src, 'hellsteel_ingot', 1.0, 100)
shaped('ingot_from_nuggets', ['NNN', 'NNN', 'NNN'], {'N': 'hellsteel_nugget'}, 'hellsteel_ingot')
shapeless('nuggets_from_ingot', ['hellsteel_ingot'], 'hellsteel_nugget', 9)
shapeless('hellgate_stone', ['minecraft:obsidian', 'minecraft:obsidian', 'hellsteel_ingot'], 'hellgate_stone', 2)
shapeless('hell_spark', ['minecraft:blaze_powder', 'hellsteel_nugget', 'minecraft:flint'], 'hell_spark')
shapeless('chronicle', ['minecraft:book', 'ember_shard'], 'chronicle')
for sw, m in (('ember_brand', 'ember_shard'), ('bone_reaper', 'bone_dust'), ('blood_thirst', 'blood_vial'), ('shadow_fang', 'shadow_essence'), ('rot_cleaver', 'rot_spore')):
    shaped(sw, ['I', 'M', 'S'], {'I': 'hellsteel_ingot', 'M': m, 'S': 'minecraft:stick'}, sw)
shaped('sealbreaker', ['I', 'O', 'S'], {'I': 'hellsteel_ingot', 'O': 'obsidian_core', 'S': 'minecraft:stick'}, 'sealbreaker')
shaped('obsidian_greataxe', ['IO', 'IS', ' S'], {'I': 'hellsteel_ingot', 'O': 'obsidian_core', 'S': 'minecraft:stick'}, 'obsidian_greataxe')
shaped('hellfire_scythe', ['IIE', ' S ', ' S '], {'I': 'hellsteel_ingot', 'E': 'ember_shard', 'S': 'minecraft:stick'}, 'hellfire_scythe')
shaped('chain_whip', [' II', 'ISI', 'S  '], {'I': 'hellsteel_ingot', 'S': 'minecraft:string'}, 'chain_whip')
shaped('sovereign_blade', [' C ', 'ISI', ' T '], {'C': 'ash_crown', 'S': 'sovereign_seal', 'I': 'hellsteel_ingot', 'T': 'minecraft:stick'}, 'sovereign_blade')
for tome, m in (('fireball', 'ember_shard'), ('bone_prison', 'bone_dust'), ('blood_pact', 'blood_vial'), ('void_step', 'shadow_essence'), ('thorn_burst', 'rot_spore')):
    shapeless('tome_' + tome, ['minecraft:book', m, m, 'hellsteel_ingot'], 'tome_' + tome)
shapeless('tome_hellrain', ['tome_fireball', 'ember_shard', 'ember_shard', 'ember_shard', 'soul_ember'], 'tome_hellrain')
shapeless('tome_soul_chain', ['minecraft:book', 'soul_ember', 'soul_ember', 'soul_ember', 'hellsteel_ingot'], 'tome_soul_chain')
shapeless('tome_summon_imp', ['minecraft:book', 'ember_shard', 'ember_shard', 'bone_dust', 'hellsteel_nugget'], 'tome_summon_imp')
shapeless('tome_decree', ['minecraft:book', 'sovereign_seal', 'ash_crown'], 'tome_decree')
print('recipes:', len(os.listdir(RD)))
