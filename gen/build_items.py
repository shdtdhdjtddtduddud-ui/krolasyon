"""Builds item textures, item models, lang and the Java item table.  python3 gen/build_items.py"""
import os, sys, json
sys.path.insert(0, os.path.dirname(__file__))
from sprites import Canvas
from items_materials import MATERIALS

ROOT = os.path.join(os.path.dirname(__file__), '..')
ASSETS = os.path.join(ROOT, 'src/main/resources/assets/krolasyonbosses')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/bosses/registry')
os.makedirs(ASSETS + '/textures/item', exist_ok=True)
os.makedirs(ASSETS + '/models/item', exist_ok=True)


def load(p):
    return json.load(open(p)) if os.path.exists(p) else {}


en = load(f'{ASSETS}/lang/en_us.json')
tr = load(f'{ASSETS}/lang/tr_tr.json')
rows = []


def emit_generated(iid, canvas_fn, size=16, parent='minecraft:item/generated'):
    c = canvas_fn(Canvas(size))
    c.to_image().save(f'{ASSETS}/textures/item/{iid}.png')
    with open(f'{ASSETS}/models/item/{iid}.json', 'w') as f:
        json.dump({'parent': parent, 'textures': {'layer0': f'krolasyonbosses:item/{iid}'}}, f)


for iid, ttr, ten, fn, rarity in MATERIALS:
    emit_generated(iid, fn)
    en[f'item.krolasyonbosses.{iid}'] = ten
    tr[f'item.krolasyonbosses.{iid}'] = ttr
    rows.append((iid, rarity))

with open(f'{JAVA}/MaterialTable.java', 'w') as f:
    f.write('// GENERATED by gen/build_items.py - do not edit by hand\npackage com.krolasyon.bosses.registry;\n\nfinal class MaterialTable {\n    private MaterialTable() {}\n\n'
            '    /** id, rarity */\n    static final String[][] ROWS = {\n' + ''.join(f'        {{"{i}", "{r}"}},\n' for i, r in rows) + '    };\n}\n')
json.dump(en, open(f'{ASSETS}/lang/en_us.json', 'w'), indent=1, ensure_ascii=False)
json.dump(tr, open(f'{ASSETS}/lang/tr_tr.json', 'w'), indent=1, ensure_ascii=False)
print('items:', len(rows))
