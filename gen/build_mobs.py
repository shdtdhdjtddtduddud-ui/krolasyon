"""Builds every creature in gen/mobs: textures, model+animation JSON, Java spec table, lang, loot tables, egg models.
Run:  python3 gen/build_mobs.py [id ...]   (no ids = all)"""
import os, sys, json, importlib, pkgutil
sys.path.insert(0, os.path.dirname(__file__))
import mobs

ROOT = os.path.join(os.path.dirname(__file__), '..')
RES = os.path.join(ROOT, 'src/main/resources')
ASSETS = os.path.join(RES, 'assets/krolasyonbosses')
DATA = os.path.join(RES, 'data/krolasyonbosses')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/bosses/entity/mob')
for d in (ASSETS + '/mobmodels', ASSETS + '/textures/entity', ASSETS + '/models/item', DATA + '/loot_tables/entities', ASSETS + '/lang'):
    os.makedirs(d, exist_ok=True)

want = set(sys.argv[1:])
ids = sorted(m.name for m in pkgutil.iter_modules(mobs.__path__))
specs = []
for mid in ids:
    mod = importlib.import_module('mobs.' + mid)
    specs.append((mod.ID, mod.SPEC))
    if want and mid not in want:
        continue
    M, P, A = mod.build()
    M.pack()
    tex, glow = P.run().images()
    tex.save(f'{ASSETS}/textures/entity/{mod.ID}.png')
    glow.save(f'{ASSETS}/textures/entity/{mod.ID}_glow.png')
    j = M.to_json()
    j['anims'] = {k.lower(): a.to_json() for k, a in A.items()}
    with open(f'{ASSETS}/mobmodels/{mod.ID}.json', 'w') as f:
        json.dump(j, f, separators=(',', ':'))
    print('built', mod.ID, 'tex', M.tw, M.th, 'bones', len(M.bones))

# ------------------------------------------------------------ java spec table
def jstr(s):
    return json.dumps(s, ensure_ascii=False)

def jf(x):
    return repr(float(x)) + 'F'

lines = []
for mid, S in specs:
    w, h, sc = S['size']
    L = f'        m.put("{mid}", new MobSpec("{mid}", Faction.{S["faction"]})'
    L += f'\n                .stats({S["hp"]}, {S.get("armor", 0)}, {S["attack"]}, {S["speed"]})'
    L += f'\n                .size({jf(w)}, {jf(h)}, {jf(sc)})'
    if S.get('fly'):
        L += f'.fly({S["fly"]})'
    L += f'.reach({S.get("reach", 2.0)})'
    if S.get('kb'):
        L += f'.kb({S["kb"]})'
    if S.get('follow'):
        L += f'.follow({S["follow"]})'
    wa, ra = S.get('anim', (1.6, 1.6))
    L += f'.anim({wa}, {ra})'
    v, p = S.get('voice', ('demon', 1.0))
    L += f'.voice("{v}", {jf(p)})'
    ea, eb = S.get('egg', (0x333333, 0xCC3333))
    L += f'.egg(0x{ea:06X}, 0x{eb:06X})'
    sw, smin, smax, sb = S.get('spawn', (0, 1, 1, []))
    L += f'.spawn({sw}, {smin}, {smax}' + ''.join(f', "{b}"' for b in sb) + ')'
    L += f'.xp({S.get("xp", 10)}, {S.get("death_ticks", 24)})'
    if S.get('head'):
        L += f'.head("{S["head"]}")'
    if S.get('shadow'):
        L += f'.shadow({jf(S["shadow"])})'
    for ab in S['abilities']:
        a = f'Ab.of(Ab.Kind.{ab["kind"]}, "{ab["anim"]}")'
        dur, *hits = ab.get('time', (20, 8))
        a += f'.time({dur}' + ''.join(f', {x}' for x in hits) + ')'
        a += f'.cd({ab.get("cd", 100)})'
        if 'w' in ab:
            a += f'.w({ab["w"]})'
        if 'range' in ab:
            a += f'.range({ab["range"][0]}, {ab["range"][1]})'
        a += f'.dmg({jf(ab.get("dmg", 1.0))})'
        if 'p' in ab:
            a += f'.p({ab["p"][0]}, {ab["p"][1]})'
        a += f'.color(0x{ab.get("color", 0xFFFFFF):06X})'
        if 'fx' in ab:
            a += f'.fx("{ab["fx"]}")'
        if 'eff' in ab:
            a += f'.eff("{ab["eff"][0]}", {ab["eff"][1]}, {ab["eff"][2]})'
        if 'summon' in ab:
            a += f'.summon("{ab["summon"]}")'
        if ab.get('los'):
            a += '.los()'
        if ab.get('air'):
            a += '.air()'
        L += f'\n                .ab({a})'
    L += ');'
    lines.append(L)
with open(f'{JAVA}/MobSpecTable.java', 'w') as f:
    f.write('// GENERATED by gen/build_mobs.py - do not edit by hand\npackage com.krolasyon.bosses.entity.mob;\n\n'
            'import com.krolasyon.bosses.faction.Faction;\n\nimport java.util.Map;\n\n'
            'final class MobSpecTable {\n    private MobSpecTable() {}\n\n    static void fill(Map<String, MobSpec> m) {\n' + '\n'.join(lines) + '\n    }\n}\n')

# ------------------------------------------------------------ egg models, loot tables, lang
FAC_TR = {'EMBER': 'Kor Hanedanı', 'BONE': 'Kemik Krallığı', 'BLOOD': 'Kan Konseyi', 'SHADOW': 'Gölge Tarikatı', 'ROT': 'Çürük Divanı', 'OUTCAST': 'Yetimler'}
FAC_EN = {'EMBER': 'Ember Dominion', 'BONE': 'Bone Kingdom', 'BLOOD': 'Blood Conclave', 'SHADOW': 'Shadow Covenant', 'ROT': 'Rot Court', 'OUTCAST': 'Outcasts'}

def load(p):
    return json.load(open(p)) if os.path.exists(p) else {}

en = load(f'{ASSETS}/lang/en_us.json')
tr = load(f'{ASSETS}/lang/tr_tr.json')
spawns = {}
bestiary = {}
for mid, S in specs:
    with open(f'{ASSETS}/models/item/{mid}_spawn_egg.json', 'w') as f:
        json.dump({'parent': 'minecraft:item/template_spawn_egg'}, f)
    pools = []
    for item, mn, mx, ch in S.get('drops', []):
        e = {'type': 'minecraft:item', 'name': item, 'functions': [
            {'function': 'minecraft:set_count', 'count': {'type': 'minecraft:uniform', 'min': mn, 'max': mx}},
            {'function': 'minecraft:looting_enchant', 'count': {'type': 'minecraft:uniform', 'min': 0, 'max': 1}}]}
        pools.append({'rolls': 1, 'conditions': [{'condition': 'minecraft:random_chance_with_looting', 'chance': ch, 'looting_multiplier': 0.08}], 'entries': [e]})
    with open(f'{DATA}/loot_tables/entities/{mid}.json', 'w') as f:
        json.dump({'type': 'minecraft:entity', 'pools': pools}, f, indent=1)
    en[f'entity.krolasyonbosses.{mid}'] = S['en']
    tr[f'entity.krolasyonbosses.{mid}'] = S['tr']
    en[f'item.krolasyonbosses.{mid}_spawn_egg'] = S['en'] + ' Spawn Egg'
    tr[f'item.krolasyonbosses.{mid}_spawn_egg'] = S['tr'] + ' Çağırma Yumurtası'
    en[f'bestiary.krolasyonbosses.{mid}'] = S.get('lore_en', S['lore'])
    tr[f'bestiary.krolasyonbosses.{mid}'] = S['lore']
    spawns[mid] = dict(weight=S['spawn'][0], min=S['spawn'][1], max=S['spawn'][2], biomes=S['spawn'][3])
    bestiary[mid] = dict(faction=S['faction'], tr=S['tr'], en=S['en'], hp=S['hp'], boss=False)
for k, v in FAC_TR.items():
    tr[f'faction.krolasyonbosses.{k.lower()}'] = v
    en[f'faction.krolasyonbosses.{k.lower()}'] = FAC_EN[k]
json.dump(en, open(f'{ASSETS}/lang/en_us.json', 'w'), indent=1, ensure_ascii=False)
json.dump(tr, open(f'{ASSETS}/lang/tr_tr.json', 'w'), indent=1, ensure_ascii=False)
json.dump(spawns, open(os.path.join(os.path.dirname(__file__), '_spawns.json'), 'w'), indent=1)
print('spec table:', len(specs), 'mobs')
