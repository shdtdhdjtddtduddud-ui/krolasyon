import os, time
import tex as T
import mobs

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'main')
TEXD = os.path.join(ROOT, 'resources', 'assets', 'sololeveling', 'textures', 'entity')
JAVA = os.path.join(ROOT, 'java', 'com', 'krolasyon', 'sololeveling', 'client', 'model', 'GenModels.java')


def run(only=None):
    os.makedirs(TEXD, exist_ok=True)
    methods, cases_layer, cases_bones, cases_rig = [], [], [], []
    for name, m in mobs.MODELS.items():
        t0 = time.time()
        m.pack()
        if not only or name in only:
            img, glow = m.paint()
            T.save(img, os.path.join(TEXD, name + '.png'))
            T.save(glow, os.path.join(TEXD, name + '_glow.png'))
        enum = name.upper()
        methods.append(f'    private static LayerDefinition {name}() {{\n{m.java()}\n    }}\n')
        cases_layer.append(f'            case {enum} -> {name}();')
        paths = ', '.join(f'"{p}"' for p in m.paths())
        cases_bones.append(f'            case {enum} -> new String[]{{{paths}}};')
        rig, freq, amp, lean, two, scale, shadow = mobs.RIGS[name]
        cases_rig.append(f'            case {enum} -> new Rig(RigType.{rig}, {freq}F, {amp}F, {lean}F, {str(two).lower()}, {scale}F, {shadow}F);')
        print(f'{name}: {len(m.cubes)} cubes, tex {m.tex_w}x{m.tex_h} x{m.res} ({time.time() - t0:.1f}s)')
    src = f'''package com.krolasyon.sololeveling.client.model;

import com.krolasyon.sololeveling.entity.MobKind;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

/** GENERATED by gen/build_mobs.py — do not edit by hand. */
public final class GenModels {{
    public enum RigType {{ BIPED, QUAD, SERPENT, CENTIPEDE }}

    public record Rig(RigType type, float walkFreq, float walkAmp, float lean, boolean twoHanded, float scale, float shadow) {{}}

    private GenModels() {{}}

    public static LayerDefinition create(MobKind k) {{
        return switch (k) {{
{chr(10).join(cases_layer)}
        }};
    }}

    public static String[] bones(MobKind k) {{
        return switch (k) {{
{chr(10).join(cases_bones)}
        }};
    }}

    public static Rig rig(MobKind k) {{
        return switch (k) {{
{chr(10).join(cases_rig)}
        }};
    }}

{chr(10).join(methods)}}}
'''
    with open(JAVA, 'w') as f:
        f.write(src)


if __name__ == '__main__':
    import sys
    run(sys.argv[1:] or None)
