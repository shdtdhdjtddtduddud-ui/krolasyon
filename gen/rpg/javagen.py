"""Writes RpgDefs.java (enums + content tables) from defs.py."""
import os
import defs

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
OUT = os.path.join(ROOT, 'src/main/java/com/krolasyon/bosses/rpg/def/RpgDefs.java')


def jstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def enum(name, values, extra=''):
    return f"    public enum {name} {{ {', '.join(values)}; {extra}}}\n"


def mon(m):
    parts = ' | '.join(f'P_{p}' for p in m.parts) or '0'
    traits = ' | '.join(f'T_{t}' for t in m.traits) or '0'
    abil = ', '.join(f'Ability.{a}' for a in m.abilities)
    regs = ', '.join(f'RegionId.{r}' for r in m.regions)
    b, s, a, e = m.colors
    summon = jstr(m.summon) if m.summon else 'null'
    return (f"        add(new MonsterDef({jstr(m.id)}, {jstr(m.name)}, Archetype.{m.arch}, {m.scale}F, {m.hp}F, {m.atk}F, {m.spd}D, "
            f"0x{b:06X}, 0x{s:06X}, 0x{a:06X}, 0x{e:06X}, {parts}, new Ability[]{{{abil}}}, {traits}, "
            f"new RegionId[]{{{regs}}}, {m.armor}, {summon}, {str(m.glow).lower()}, {str(m.boss).lower()}));\n")


def main():
    out = []
    out.append("""// GENERATED by gen/rpg/javagen.py from gen/rpg/defs.py - do not edit by hand
package com.krolasyon.bosses.rpg.def;

import java.util.*;

public final class RpgDefs {
    private RpgDefs() {}

""")
    out.append(enum('Archetype', defs.ARCHETYPES))
    out.append(enum('Ability', defs.ABILITIES))
    out.append(enum('School', [s[0] for s in defs.SCHOOLS]))
    out.append(enum('SpellShape', defs.SHAPES))
    out.append(enum('SwordPassive', defs.SWORD_PASSIVES))
    out.append(enum('SwordSkill', defs.SWORD_SKILLS))
    regs = ', '.join(f'{r[0]}({jstr(r[1])}, {r[2]}, {r[3]})' for r in defs.REGIONS)
    out.append(f"""    public enum RegionId {{
        {regs};
        public final String title; public final int kingdom; public final int danger;
        RegionId(String title, int kingdom, int danger) {{ this.title = title; this.kingdom = kingdom; this.danger = danger; }}
        public boolean wild() {{ return kingdom < 0; }}
    }}
""")
    for i, p in enumerate(defs.PARTS):
        out.append(f"    public static final int P_{p} = 1 << {i};\n")
    out.append(f"    public static final String[] PART_NAMES = {{{', '.join(jstr(p.lower()) for p in defs.PARTS)}}};\n")
    for i, t in enumerate(defs.TRAITS):
        out.append(f"    public static final int T_{t} = 1 << {i};\n")
    out.append("\n")
    sch = ', '.join(f'{{{jstr(s[1])}, "{s[2]}", "{s[3]}"}}' for s in defs.SCHOOLS)
    out.append(f"    public static final String[][] SCHOOL_INFO = {{{sch}}};\n")
    out.append("""    public static String schoolName(School s) { return SCHOOL_INFO[s.ordinal()][0]; }
    public static int schoolColor(School s) { return Integer.parseInt(SCHOOL_INFO[s.ordinal()][1]); }
    public static int schoolColor2(School s) { return Integer.parseInt(SCHOOL_INFO[s.ordinal()][2]); }

    public static final List<MonsterDef> MONSTERS = new ArrayList<>();
    public static final List<MonsterDef> BOSSES = new ArrayList<>();
    public static final Map<String, MonsterDef> BY_ID = new LinkedHashMap<>();
    public static final List<SpellDef> SPELLS = new ArrayList<>();
    public static final Map<String, SpellDef> SPELL_BY_ID = new LinkedHashMap<>();
    public static final List<SwordDef> SWORDS = new ArrayList<>();

    private static void add(MonsterDef d) { (d.boss() ? BOSSES : MONSTERS).add(d); BY_ID.put(d.id(), d); }
    private static void spell(SpellDef d) { SPELLS.add(d); SPELL_BY_ID.put(d.id(), d); }

    static {
        monsters();
        bosses();
        spells();
        swords();
    }

    private static void monsters() {
""")
    for m in defs.MONSTERS:
        out.append(mon(m))
    out.append("    }\n\n    private static void bosses() {\n")
    for m in defs.BOSSES:
        out.append(mon(m))
    out.append("    }\n\n    private static void spells() {\n")
    for s in defs.SPELLS:
        out.append(f"        spell(new SpellDef({jstr(s[0])}, {jstr(s[1])}, School.{s[2]}, SpellShape.{s[3]}, {s[4]}F, {s[5]}, {s[6]}, {s[7]}));\n")
    out.append("    }\n\n    private static void swords() {\n")
    for s in defs.SWORDS:
        gem = f'0x{s[8]:06X}' if s[8] is not None else '-1'
        out.append(f"        SWORDS.add(new SwordDef({jstr(s[0])}, {jstr(s[1])}, {s[2]}F, {s[3]}F, {s[4]}, 0x{s[5]:06X}, 0x{s[6]:06X}, 0x{s[7]:06X}, {gem}, "
                   f"SwordPassive.{s[10]}, SwordSkill.{s[11]}));\n")
    out.append("    }\n}\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(''.join(out))


if __name__ == '__main__':
    main()
