def board_model(name, accent):
    bm = BM(name, size=256, ppu=4.0)
    # posts
    bm.box((1, 0, 6), (3, 14, 8), 'wood'); bm.box((13, 0, 6), (15, 14, 8), 'wood')
    bm.box((0, 14, 5.5), (16, 16, 8.5), 'wood')
    bm.box((1.5, 4, 6.4), (14.5, 14, 7.6), 'panel')
    for i, (x, y) in enumerate(((2.5, 9), (7, 6), (11, 10), (5, 11.5))):
        bm.box((x, y, 7.6), (x + 3, y + 2.6, 7.9), 'paper')
    bm.box((6.6, 11.6, 7.9), (7.4, 12.4, 8.3), 'pin')
