"""Generates textures + Java ModelPart layer definitions for the furniture mod."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from fmodels import *

ROOT = os.path.join(os.path.dirname(__file__), '..')
TEX = os.path.join(ROOT, 'src/main/resources/assets/krolasyonfurniture/textures/entity')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/furniture/client/model')
os.makedirs(TEX, exist_ok=True)
os.makedirs(JAVA, exist_ok=True)

layers = []
for name, builder in BUILDERS.items():
    m, _ = builder()
    m.pack()
    P = make_painter(m)
    board_painter(P)
    tex, _g = P.run().images()
    tex.save(os.path.join(TEX, f'{name}.png'))
    if name == 'chalkboard':
        m2, _ = chalkboard(True)
        m2.pack()
        P2 = make_painter(m2)
        board_painter(P2)
        P2.run().images()[0].save(os.path.join(TEX, 'chalkboard_clean.png'))
    fn = ''.join(p.capitalize() for p in name.split('_'))
    layers.append(f"""    public static LayerDefinition create{fn}() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{m.java_layer()}
        return LayerDefinition.create(mesh, {m.tw}, {m.th});
    }}
""")

with open(os.path.join(JAVA, 'FurnitureLayers.java'), 'w') as f:
    f.write("""// GENERATED by gen/build_f.py - do not edit by hand
package com.krolasyon.furniture.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

@SuppressWarnings("unused")
public final class FurnitureLayers {
    private FurnitureLayers() {}

""" + "\n".join(layers) + "}\n")
print('generated')
