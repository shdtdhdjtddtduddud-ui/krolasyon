"""Generates entity textures + Java model layer / animation classes for the Labirent mod."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import griever, beetle

ROOT = os.path.join(os.path.dirname(__file__), '..')
TEX = os.path.join(ROOT, 'src/main/resources/assets/labirent/textures/entity')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/labirent/client/model')
os.makedirs(TEX, exist_ok=True)
os.makedirs(JAVA, exist_ok=True)

layers = []
for name, mod in (('griever', griever), ('beetle_blade', beetle)):
    mod.M.pack()
    tex, glow = mod.P.run().images()
    tex.save(os.path.join(TEX, f'{name}.png'))
    glow.save(os.path.join(TEX, f'{name}_glow.png'))
    fn = ''.join(p.capitalize() for p in name.split('_'))
    layers.append(f"""    public static LayerDefinition create{fn}() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{mod.M.java_layer()}
        return LayerDefinition.create(mesh, {mod.M.tw}, {mod.M.th});
    }}
""")

with open(os.path.join(JAVA, 'ModelLayers.java'), 'w') as f:
    f.write("""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.labirent.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

@SuppressWarnings("unused")
public final class ModelLayers {
    private ModelLayers() {}

""" + "\n".join(layers) + "}\n")

for cls, mod in (('GrieverAnimations', griever), ('BeetleBladeAnimations', beetle)):
    body = "\n\n".join(a.java(k) for k, a in mod.A.items())
    with open(os.path.join(JAVA, f'{cls}.java'), 'w') as f:
        f.write(f"""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.labirent.client.model;

import net.minecraft.client.animation.AnimationChannel;
import net.minecraft.client.animation.AnimationDefinition;
import net.minecraft.client.animation.Keyframe;
import net.minecraft.client.animation.KeyframeAnimations;

public final class {cls} {{
    private {cls}() {{}}

{body}
}}
""")
print('generated')
