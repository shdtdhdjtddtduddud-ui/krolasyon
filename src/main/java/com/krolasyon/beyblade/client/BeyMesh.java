package com.krolasyon.beyblade.client;

import com.krolasyon.beyblade.LibraBeyblade;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.client.renderer.LightTexture;
import net.minecraft.resources.ResourceLocation;
import org.joml.Matrix3f;
import org.joml.Matrix4f;

import java.io.DataInputStream;
import java.io.BufferedInputStream;
import java.io.InputStream;

/**
 * Beyblade mesh generated by gen/beyblade/<name>_model.py from the reference artwork.
 * Model units: radius 1, y = 0 at the tip point.
 */
public final class BeyMesh {

    /** Flame Libra: disc radius 315 px, texture window half size 322 px */
    public static final BeyMesh LIBRA = new BeyMesh("libra", 1.30F, 1.46F, 322F / 315F);
    /** L-Drago Destruction: nominal radius 345 px, texture window half size 382 px */
    public static final BeyMesh LDRAGO = new BeyMesh("ldrago", 0.98F, 1.18F, 382F / 345F);

    /** Rock Leone: radius 163 px, texture window half size 172 px */
    public static final BeyMesh LEONE = new BeyMesh("leone", 1.27F, 1.48F, 172F / 163F);

    /** Earth Eagle: radius 207 px, texture window half size 216 px */
    public static final BeyMesh EAGLE = new BeyMesh("eagle", 1.27F, 1.48F, 216F / 207F);

    /** Storm Pegasus: radius 227 px, texture window half size 238 px */
    public static final BeyMesh PEGASUS = new BeyMesh("pegasus", 1.03F, 1.24F, 238F / 227F);

    /** the ten common beyblades share one mesh (common_mesh.bin) with their own textures */
    private static final BeyMesh[] COMMON = new BeyMesh[10];

    public static BeyMesh common(int variant) {
        int v = Math.floorMod(variant, COMMON.length);
        if (COMMON[v] == null) COMMON[v] = new BeyMesh("common_" + v, "common", 1.07F, 1.26F, 1.04F);
        return COMMON[v];
    }

    public static BeyMesh of(com.krolasyon.beyblade.entity.BeybladeEntity e) {
        if (e instanceof com.krolasyon.beyblade.entity.CommonBeybladeEntity c) return common(c.getVariant());
        return of(e.kindId());
    }

    public static BeyMesh of(String kind) {
        if (kind.startsWith("common_")) return common(Integer.parseInt(kind.substring(7)));
        return switch (kind) {
            case "pegasus" -> PEGASUS;
            case "eagle" -> EAGLE;
            case "ldrago" -> LDRAGO;
            case "leone" -> LEONE;
            default -> LIBRA;
        };
    }

    public final ResourceLocation FACE, GLOW, PARTS;
    public final float TOP_Y, HEIGHT;
    private final String name;
    private final float ghostHalf;

    private BeyMesh(String name, float topY, float height, float ghostHalf) {
        this(name, name, topY, height, ghostHalf);
    }

    private BeyMesh(String name, String meshName, float topY, float height, float ghostHalf) {
        this.name = meshName;
        this.FACE = new ResourceLocation(LibraBeyblade.MODID, "textures/entity/" + name + "_face.png");
        this.GLOW = new ResourceLocation(LibraBeyblade.MODID, "textures/entity/" + name + "_glow.png");
        this.PARTS = new ResourceLocation(LibraBeyblade.MODID, "textures/entity/" + name + "_parts.png");
        this.TOP_Y = topY;
        this.HEIGHT = height;
        this.ghostHalf = ghostHalf;
    }

    private static final int TOP = 0, SIDE = 1, PART = 2;
    private float[][] groups;

    private float[][] groups() {
        if (groups == null) {
            float[][] g = new float[3][];
            try (InputStream raw = BeyMesh.class.getResourceAsStream("/assets/librabeyblade/models/" + name + "_mesh.bin")) {
                if (raw == null) throw new IllegalStateException(name + "_mesh.bin missing");
                DataInputStream in = new DataInputStream(new BufferedInputStream(raw));
                in.readInt();
                int n = in.readInt();
                for (int i = 0; i < n; i++) {
                    int id = in.readInt();
                    int quads = in.readInt();
                    float[] data = new float[quads * 4 * 8];
                    for (int k = 0; k < data.length; k++) data[k] = in.readFloat();
                    if (id >= 0 && id < 3) g[id] = data;
                }
            } catch (Exception e) {
                throw new RuntimeException("Failed to load beyblade mesh " + name, e);
            }
            for (int i = 0; i < 3; i++) if (g[i] == null) g[i] = new float[0];
            groups = g;
        }
        return groups;
    }

    /** solid model: face/sides with the artwork texture, track + tip with the parts texture */
    public void render(PoseStack pose, MultiBufferSource buffers, int light, int overlay, float r, float g, float b) {
        float[][] gr = groups();
        VertexConsumer vc = buffers.getBuffer(RenderType.entityCutoutNoCull(FACE));
        emit(pose, vc, gr[TOP], light, overlay, r, g, b, 1F);
        emit(pose, vc, gr[SIDE], light, overlay, r, g, b, 1F);
        vc = buffers.getBuffer(RenderType.entityCutoutNoCull(PARTS));
        emit(pose, vc, gr[PART], light, overlay, r, g, b, 1F);
    }

    /** additive emissive pass over the top surface (clear wheel + emblem glow) */
    public void renderGlow(PoseStack pose, MultiBufferSource buffers, float r, float g, float b) {
        if (r <= 0.003F && g <= 0.003F && b <= 0.003F) return;
        VertexConsumer vc = buffers.getBuffer(RenderType.eyes(GLOW));
        emit(pose, vc, groups()[TOP], LightTexture.FULL_BRIGHT, OverlayTexture.NO_OVERLAY, r, g, b, 1F);
    }

    /** a flat translucent copy of the face, used for spin motion blur and afterimages */
    public void renderGhostDisc(PoseStack pose, MultiBufferSource buffers, int light, float alpha, float y) {
        VertexConsumer vc = buffers.getBuffer(RenderType.entityTranslucent(FACE));
        Matrix4f m = pose.last().pose();
        Matrix3f n = pose.last().normal();
        float s = ghostHalf;   // texture window half size in model units
        gv(vc, m, n, -s, y, -s, 0, 0, light, alpha);
        gv(vc, m, n, -s, y, s, 0, 1, light, alpha);
        gv(vc, m, n, s, y, s, 1, 1, light, alpha);
        gv(vc, m, n, s, y, -s, 1, 0, light, alpha);
    }

    private static void gv(VertexConsumer vc, Matrix4f m, Matrix3f n, float x, float y, float z, float u, float v, int light, float a) {
        vc.vertex(m, x, y, z).color(1F, 1F, 1F, a).uv(u, v).overlayCoords(OverlayTexture.NO_OVERLAY).uv2(light).normal(n, 0, 1, 0).endVertex();
    }

    private static void emit(PoseStack pose, VertexConsumer vc, float[] d, int light, int overlay, float r, float g, float b, float a) {
        Matrix4f m = pose.last().pose();
        Matrix3f n = pose.last().normal();
        for (int i = 0; i < d.length; i += 8) {
            vc.vertex(m, d[i], d[i + 1], d[i + 2]).color(r, g, b, a).uv(d[i + 3], d[i + 4]).overlayCoords(overlay).uv2(light)
                    .normal(n, d[i + 5], d[i + 6], d[i + 7]).endVertex();
        }
    }
}
