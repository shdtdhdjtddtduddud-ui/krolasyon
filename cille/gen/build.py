"""Generates textures + Java model layer / animation classes into the Cille mod source tree."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import kabkaba, behmud, sarkan, nirumend, extras, smooth

ROOT = os.path.join(os.path.dirname(__file__), '..')
ASSETS = os.path.join(ROOT, 'src/main/resources/assets/cille')
TEX = os.path.join(ASSETS, 'textures/entity')
ITEM = os.path.join(ASSETS, 'textures/item')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/cille/client/model')
for d in (TEX, ITEM, JAVA):
    os.makedirs(d, exist_ok=True)


def layer(fn, model):
    return f"""    public static LayerDefinition create{fn}() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{model.java_layer()}
        return LayerDefinition.create(mesh, {model.tw}, {model.th});
    }}
"""


layers = []
kabkaba.M.pack()
tex, glow = kabkaba.P.run().images()
tex.save(os.path.join(TEX, 'kabkaba.png'))
glow.save(os.path.join(TEX, 'kabkaba_glow.png'))
layers.append(layer('Kabkaba', kabkaba.M))
behmud.M.pack()
tex, glow = behmud.P.run().images()
tex.save(os.path.join(TEX, 'behmud.png'))
glow.save(os.path.join(TEX, 'behmud_glow.png'))
layers.append(layer('Behmud', behmud.M))
sarkan.M.pack()
tex, glow = sarkan.P.run().images()
tex.save(os.path.join(TEX, 'sarkan.png'))
glow.save(os.path.join(TEX, 'sarkan_glow.png'))
layers.append(layer('Sarkan', sarkan.M))
nirumend.M.pack()
tex, glow = nirumend.P.run().images()
tex.save(os.path.join(TEX, 'nirumend.png'))
glow.save(os.path.join(TEX, 'nirumend_glow.png'))
layers.append(layer('Nirumend', nirumend.M))
t, g = extras.fish_painter().run().images()
t.save(os.path.join(TEX, 'fish.png'))
g.save(os.path.join(TEX, 'fish_glow.png'))
layers.append(layer('Fish', extras.FISH))

for kind, name in ((0, 'marble'), (1, 'shield'), (2, 'black_hole_core')):
    t, g = extras.sphere_painter(kind).run().images()
    t.save(os.path.join(TEX, f'{name}.png'))
    g.save(os.path.join(TEX, f'{name}_glow.png'))
layers.append(layer('Sphere', extras.SPH))

t, g = extras.spike_painter().run().images()
t.save(os.path.join(TEX, 'shadow_spike.png'))
g.save(os.path.join(TEX, 'shadow_spike_glow.png'))
layers.append(layer('ShadowSpike', extras.SPK))
t, g = extras.rock_spike_painter().run().images()
t.save(os.path.join(TEX, 'rock_spike.png'))
g.save(os.path.join(TEX, 'rock_spike_glow.png'))

extras.disk_texture().save(os.path.join(TEX, 'black_hole_disk.png'))
extras.marble_icon().save(os.path.join(ITEM, 'kabkaba_misketi.png'))
extras.marble_glass_tex().save(os.path.join(TEX, 'marble_glass.png'))
extras.shield_tex().save(os.path.join(TEX, 'shield_sphere.png'))
extras.hole_tex().save(os.path.join(TEX, 'hole_sphere.png'))
extras.halo_tex().save(os.path.join(TEX, 'hole_halo.png'))
extras.star_tex().save(os.path.join(TEX, 'star.png'))
extras.water_tex().save(os.path.join(TEX, 'water_swirl.png'))
extras.behmud_icon().save(os.path.join(ITEM, 'behmud_misketi.png'))
extras.sand_tex().save(os.path.join(TEX, 'sand_swirl.png'))
extras.sarkan_icon().save(os.path.join(ITEM, 'sarkan_misketi.png'))
extras.electric_tex().save(os.path.join(TEX, 'electric_sphere.png'))
extras.nirumend_icon().save(os.path.join(ITEM, 'nirumend_misketi.png'))

MESH = os.path.join(ASSETS, 'meshes')
os.makedirs(MESH, exist_ok=True)
for name, mod in (('kabkaba', kabkaba), ('behmud', behmud), ('sarkan', sarkan), ('nirumend', nirumend)):
    _, tris = smooth.build(mod.M, mod.P, os.path.join(MESH, f'{name}.cmsh'))
    print('smooth mesh', name, tris, 'triangles')

with open(os.path.join(JAVA, 'ModelLayers.java'), 'w') as f:
    f.write("""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.cille.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

@SuppressWarnings("unused")
public final class ModelLayers {
    private ModelLayers() {}

""" + "\n".join(layers) + "}\n")

for cls, mod in (('KabkabaAnimations', kabkaba), ('BehmudAnimations', behmud), ('SarkanAnimations', sarkan), ('NirumendAnimations', nirumend)):
    body = "\n\n".join(a.java(k) for k, a in mod.A.items())
    with open(os.path.join(JAVA, f'{cls}.java'), 'w') as f:
        f.write(f"""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.cille.client.model;

import net.minecraft.client.animation.AnimationChannel;
import net.minecraft.client.animation.AnimationDefinition;
import net.minecraft.client.animation.Keyframe;
import net.minecraft.client.animation.KeyframeAnimations;

public final class {cls} {{
    private {cls}() {{}}

{body}
}}
""")
print('generated')
