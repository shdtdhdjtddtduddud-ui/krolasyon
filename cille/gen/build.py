"""Generates textures + Java model layer / animation classes into the Cille mod source tree."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import kabkaba, extras

ROOT = os.path.join(os.path.dirname(__file__), '..')
ASSETS = os.path.join(ROOT, 'src/main/resources/assets/cille')
TEX = os.path.join(ASSETS, 'textures/entity')
ITEM = os.path.join(ASSETS, 'textures/item')
JAVA = os.path.join(ROOT, 'src/main/java/com/krolasyon/cille/client/model')
for d in (TEX, ITEM, JAVA):
    os.makedirs(d, exist_ok=True)


def layer(fn, model):
    return f"""    public static LayerDefinition create{fn}() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{model.java_layer()}
        return LayerDefinition.create(mesh, {model.tw}, {model.th});
    }}
"""


layers = []
kabkaba.M.pack()
tex, glow = kabkaba.P.run().images()
tex.save(os.path.join(TEX, 'kabkaba.png'))
glow.save(os.path.join(TEX, 'kabkaba_glow.png'))
layers.append(layer('Kabkaba', kabkaba.M))

for kind, name in ((0, 'marble'), (1, 'shield'), (2, 'black_hole_core')):
    t, g = extras.sphere_painter(kind).run().images()
    t.save(os.path.join(TEX, f'{name}.png'))
    g.save(os.path.join(TEX, f'{name}_glow.png'))
layers.append(layer('Sphere', extras.SPH))

t, g = extras.spike_painter().run().images()
t.save(os.path.join(TEX, 'shadow_spike.png'))
g.save(os.path.join(TEX, 'shadow_spike_glow.png'))
layers.append(layer('ShadowSpike', extras.SPK))

extras.disk_texture().save(os.path.join(TEX, 'black_hole_disk.png'))
extras.marble_icon().save(os.path.join(ITEM, 'kabkaba_misketi.png'))

with open(os.path.join(JAVA, 'ModelLayers.java'), 'w') as f:
    f.write("""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.cille.client.model;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

@SuppressWarnings("unused")
public final class ModelLayers {
    private ModelLayers() {}

""" + "\n".join(layers) + "}\n")

body = "\n\n".join(a.java(k) for k, a in kabkaba.A.items())
with open(os.path.join(JAVA, 'KabkabaAnimations.java'), 'w') as f:
    f.write(f"""// GENERATED by gen/build.py - do not edit by hand
package com.krolasyon.cille.client.model;

import net.minecraft.client.animation.AnimationChannel;
import net.minecraft.client.animation.AnimationDefinition;
import net.minecraft.client.animation.Keyframe;
import net.minecraft.client.animation.KeyframeAnimations;

public final class KabkabaAnimations {{
    private KabkabaAnimations() {{}}

{body}
}}
""")
print('generated', sum(len(b.cubes) for b in kabkaba.M.bones.values()), 'cubes')
