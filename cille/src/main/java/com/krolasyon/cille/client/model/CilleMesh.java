package com.krolasyon.cille.client.model;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.mojang.logging.LogUtils;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.LightTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.Resource;
import org.joml.Matrix3f;
import org.joml.Matrix4f;
import org.slf4j.Logger;

import javax.annotation.Nullable;
import java.io.DataInputStream;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * Smooth triangle mesh of a Cille (generated by gen/smooth.py): one vertex-coloured surface per bone, drawn with
 * that bone's animated ModelPart transform. Glowing vertices (eyes, gems, stars) are drawn full-bright.
 */
public final class CilleMesh {
    private static final Logger LOG = LogUtils.getLogger();
    private static final Map<ResourceLocation, Optional<CilleMesh>> CACHE = new HashMap<>();

    public static final class Bone {
        public final String name, parent;
        final float[] pos, nrm, col;
        final boolean[] glow;
        final int[] tris;

        Bone(String name, String parent, float[] pos, float[] nrm, float[] col, boolean[] glow, int[] tris) {
            this.name = name;
            this.parent = parent;
            this.pos = pos;
            this.nrm = nrm;
            this.col = col;
            this.glow = glow;
            this.tris = tris;
        }

        public boolean hasGeometry() { return tris.length > 0; }

        public void draw(PoseStack.Pose p, VertexConsumer vc, int light, int overlay, float r, float g, float b, float a) {
            Matrix4f m = p.pose();
            Matrix3f n = p.normal();
            for (int t = 0; t < tris.length; t += 3) {
                // entity render types draw quads: each triangle is sent as a quad with a repeated last corner
                for (int k = 0; k < 4; k++) {
                    int i = tris[t + Math.min(k, 2)];
                    int i3 = i * 3;
                    float x = pos[i3], y = pos[i3 + 1], z = pos[i3 + 2];
                    vc.vertex(m, x, y, z)
                            .color(col[i3] * r, col[i3 + 1] * g, col[i3 + 2] * b, a)
                            .uv((x + z) * 0.5F, y * 0.5F)
                            .overlayCoords(overlay)
                            .uv2(glow[i] ? LightTexture.FULL_BRIGHT : light)
                            .normal(n, nrm[i3], nrm[i3 + 1], nrm[i3 + 2])
                            .endVertex();
                }
            }
        }
    }

    public final List<Bone> bones;

    private CilleMesh(List<Bone> bones) {
        this.bones = bones;
    }

    @Nullable
    public static CilleMesh get(ResourceLocation loc) {
        return CACHE.computeIfAbsent(loc, CilleMesh::load).orElse(null);
    }

    private static Optional<CilleMesh> load(ResourceLocation loc) {
        Optional<Resource> res = Minecraft.getInstance().getResourceManager().getResource(loc);
        if (res.isEmpty()) {
            LOG.warn("Cille mesh {} not found, using the cube model", loc);
            return Optional.empty();
        }
        try (InputStream in = res.get().open(); DataInputStream d = new DataInputStream(new java.io.BufferedInputStream(in))) {
            byte[] magic = new byte[4];
            d.readFully(magic);
            if (magic[0] != 'C' || magic[1] != 'M' || magic[2] != 'S' || magic[3] != 'H') throw new IllegalStateException("bad mesh header");
            d.readInt();
            int count = d.readInt();
            List<Bone> bones = new ArrayList<>(count);
            for (int bi = 0; bi < count; bi++) {
                String name = d.readUTF();
                String parent = d.readUTF();
                int nv = d.readInt(), nt = d.readInt();
                float[] pos = new float[nv * 3], nrm = new float[nv * 3], col = new float[nv * 3];
                boolean[] glow = new boolean[nv];
                for (int i = 0; i < nv; i++) {
                    for (int k = 0; k < 3; k++) pos[i * 3 + k] = d.readFloat();
                    for (int k = 0; k < 3; k++) nrm[i * 3 + k] = d.readFloat();
                    for (int k = 0; k < 3; k++) col[i * 3 + k] = d.readUnsignedByte() / 255F;
                    glow[i] = d.readUnsignedByte() != 0;
                }
                int[] tris = new int[nt * 3];
                for (int i = 0; i < tris.length; i++) tris[i] = d.readInt();
                bones.add(new Bone(name, parent, pos, nrm, col, glow, tris));
            }
            LOG.info("Loaded Cille mesh {} ({} bones)", loc, count);
            return Optional.of(new CilleMesh(bones));
        } catch (Exception e) {
            LOG.error("Failed to load Cille mesh {}", loc, e);
            return Optional.empty();
        }
    }
}
