FACING_Y = {'north': 0, 'east': 90, 'south': 180, 'west': 270}


def face(texture, uv=None):
    f = {'texture': texture}
    if uv:
        f['uv'] = uv
    return f


def box(frm, to, tex_all, north=None, south=None, up=None, down=None, uvs=None):
    faces = {}
    for d in ('north', 'south', 'east', 'west', 'up', 'down'):
        t = {'north': north, 'south': south, 'up': up, 'down': down}.get(d) or tex_all
        faces[d] = face(t)
    return {'from': frm, 'to': to, 'faces': faces}


def gen_json():
    bs = os.path.join(ASSETS, 'blockstates'); bm = os.path.join(ASSETS, 'models/block'); im = os.path.join(ASSETS, 'models/item')
