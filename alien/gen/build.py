# ------------------------------------------------------------------ recipes
def gen_recipes():
    rd = os.path.join(DATA, 'recipes')

    def shaped(name, pattern, key, count=1):
        wj(f'{rd}/{name}.json', {'type': 'minecraft:crafting_shaped', 'pattern': pattern,
                                 'key': {k: {'item': v} for k, v in key.items()}, 'result': {'item': f'{M}:{name}', 'count': count}})

    def shapeless(name, items, count=1):
        wj(f'{rd}/{name}.json', {'type': 'minecraft:crafting_shapeless', 'ingredients': [{'item': i} for i in items],
                                 'result': {'item': f'{M}:{name}', 'count': count}})

    shaped('motion_tracker', ['IGI', 'IRI', ' I '], {'I': 'minecraft:iron_ingot', 'G': 'minecraft:glass_pane', 'R': 'minecraft:compass'})
    shaped('flamethrower', ['  F', 'IBI', 'I  '], {'F': 'minecraft:flint_and_steel', 'I': 'minecraft:iron_ingot', 'B': 'minecraft:blaze_powder'})
    shapeless('fuel', ['minecraft:glass_bottle', 'minecraft:coal', 'minecraft:blaze_powder'], 2)
    shapeless('noisemaker', ['minecraft:iron_nugget', 'minecraft:redstone', 'minecraft:note_block'], 2)
    shapeless('flare', ['minecraft:paper', 'minecraft:gunpowder', 'minecraft:redstone'], 2)
    shapeless('medkit', ['minecraft:paper', 'minecraft:white_wool', 'minecraft:glistering_melon_slice'], 1)
    shaped('flashlight', ['GII', ' I '], {'G': 'minecraft:glowstone_dust', 'I': 'minecraft:iron_ingot'})


